-- Hand-written workaround migration (same convention as 20260823000000/000003/000005/000006).
--
-- Payload's internal system collections (`payload-preferences`,
-- `payload-locked-documents`, its internal KV store, and its own
-- `payload_migrations` bookkeeping table) were never hand-created — they're
-- normally auto-created by `payload migrate` or dev schema-push, both of
-- which are unavailable in this workspace (Root Cause 1: tsx space-in-path
-- bug; Root Cause 2: push:false is required to avoid the 90s+ hang).
--
-- Exact column/index/FK DDL below was NOT guessed — it was generated by
-- Payload's own drizzle-kit schema generator (`payload.db.createMigration`,
-- called via a temporary debug route hitting the already-initialized
-- Payload instance, then deleted). This is ground truth from Payload's own
-- schema, scoped down to only the tables that don't already exist
-- (products/media/users/users_sessions are excluded — already hand-created).
--
-- Symptom this fixes: admin panel nav/layout preferences failing with
-- `relation "payload_preferences" does not exist` after logging in.

create table if not exists payload_kv (
  id   uuid primary key default gen_random_uuid(),
  key  varchar not null,
  data jsonb not null
);

create table if not exists payload_locked_documents (
  id          uuid primary key default gen_random_uuid(),
  global_slug varchar,
  updated_at  timestamptz(3) not null default now(),
  created_at  timestamptz(3) not null default now()
);

create table if not exists payload_locked_documents_rels (
  id         serial primary key,
  "order"    integer,
  parent_id  uuid not null references payload_locked_documents(id) on delete cascade,
  path       varchar not null,
  products_id uuid references products(id) on delete cascade,
  media_id    uuid references media(id) on delete cascade,
  users_id    uuid references users(id) on delete cascade
);

create table if not exists payload_preferences (
  id         uuid primary key default gen_random_uuid(),
  key        varchar,
  value      jsonb,
  updated_at timestamptz(3) not null default now(),
  created_at timestamptz(3) not null default now()
);

create table if not exists payload_preferences_rels (
  id        serial primary key,
  "order"   integer,
  parent_id uuid not null references payload_preferences(id) on delete cascade,
  path      varchar not null,
  users_id  uuid references users(id) on delete cascade
);

create table if not exists payload_migrations (
  id         uuid primary key default gen_random_uuid(),
  name       varchar,
  batch      numeric,
  updated_at timestamptz(3) not null default now(),
  created_at timestamptz(3) not null default now()
);

create unique index if not exists payload_kv_key_idx on payload_kv using btree (key);

create index if not exists payload_locked_documents_global_slug_idx on payload_locked_documents using btree (global_slug);
create index if not exists payload_locked_documents_updated_at_idx on payload_locked_documents using btree (updated_at);
create index if not exists payload_locked_documents_created_at_idx on payload_locked_documents using btree (created_at);

create index if not exists payload_locked_documents_rels_order_idx on payload_locked_documents_rels using btree ("order");
create index if not exists payload_locked_documents_rels_parent_idx on payload_locked_documents_rels using btree (parent_id);
create index if not exists payload_locked_documents_rels_path_idx on payload_locked_documents_rels using btree (path);
create index if not exists payload_locked_documents_rels_products_id_idx on payload_locked_documents_rels using btree (products_id);
create index if not exists payload_locked_documents_rels_media_id_idx on payload_locked_documents_rels using btree (media_id);
create index if not exists payload_locked_documents_rels_users_id_idx on payload_locked_documents_rels using btree (users_id);

create index if not exists payload_preferences_key_idx on payload_preferences using btree (key);
create index if not exists payload_preferences_updated_at_idx on payload_preferences using btree (updated_at);
create index if not exists payload_preferences_created_at_idx on payload_preferences using btree (created_at);

create index if not exists payload_preferences_rels_order_idx on payload_preferences_rels using btree ("order");
create index if not exists payload_preferences_rels_parent_idx on payload_preferences_rels using btree (parent_id);
create index if not exists payload_preferences_rels_path_idx on payload_preferences_rels using btree (path);
create index if not exists payload_preferences_rels_users_id_idx on payload_preferences_rels using btree (users_id);

create index if not exists payload_migrations_updated_at_idx on payload_migrations using btree (updated_at);
create index if not exists payload_migrations_created_at_idx on payload_migrations using btree (created_at);
